// 30 wedding invitation templates expressed as style presets.
// One renderer (InvitationRenderer) reads these tokens and draws a full,
// scrollable mobile invitation — so adding a template never needs new code.

export type TemplateCategory = "classic" | "magazine";

export type CoverLayout =
  | "centered" // 사진 위 중앙 정렬, 정통 무드
  | "bottom" // 사진 풀블리드 + 하단 타이포
  | "frame" // 여백 프레임 안의 사진 (종이 청첩장)
  | "split" // 사진 + 컬러 패널 분할
  | "arch" // 아치형 사진 프레임
  | "poster" // 거대한 타이포가 지배하는 매거진 커버
  | "editorial" // 잡지 표지 (kicker + 큰 세리프 + 라벨)
  | "overlay"; // 어두운 사진 위 글래스 패널

export type FontFamily = "serif" | "sans" | "display";

export interface TemplatePalette {
  ink: string; // 본문 글자색
  paper: string; // 배경색
  accent: string; // 포인트 컬러
  soft: string; // 보조 면 컬러
  line: string; // 라인 컬러
}

export interface Template {
  id: string;
  name: string;
  category: TemplateCategory;
  tag: string; // 화면용 한글 태그
  source: string; // 참고 무드 라벨
  description: string;
  kicker: string; // 커버 상단 영문 라벨
  accentLabel: string; // 매거진 라벨 (SERIF, GLASS 등)
  cover: CoverLayout;
  font: FontFamily;
  uppercase: boolean; // 영문 라벨 대문자 강조 여부
  grain: boolean; // 매거진 종이 질감
  coverPhoto: string;
  palette: TemplatePalette;
}

